"""data/charts.csv -> native/orp_chart_table.inc (C initializer list)."""
import csv, os
root = os.path.join(os.path.dirname(__file__), "..")
rows = list(csv.DictReader(open(os.path.join(root, "data", "charts.csv"), encoding="utf-8")))
def cstr(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\': out.append("\\" + c)
        elif 32 <= b < 127 and c != "?": out.append(c)   # avoid trigraphs
        else: out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'
lines = ["// GENERATED by tools/gen_chart_table.py from data/charts.csv - do not edit"]
for r in rows:
    cls = r["grade"].split()[0]
    lines.append("{%s, %s, %s}," % (cstr(r["title"].strip()), cstr(cls), r["constant"]))
open(os.path.join(root, "native", "orp_chart_table.inc"), "w").write("\n".join(lines) + "\n")
print(len(rows), "entries")
